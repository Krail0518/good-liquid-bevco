          location: loc, zone: tr.querySelector('.gl-atp-zone').value,
          rlu: rluRaw === '' ? null : Number(rluRaw), result: result,
          reswab_rlu: reswab, reswab_result: reResult,
          final_result: reResult || result, corrective_action: ca || null
