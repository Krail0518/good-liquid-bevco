  // ── Pure helpers (exported for tests) ─────────────────────────
  function limits(){
    var L = (typeof window.glGetLimits === 'function' && window.glGetLimits()) || {};
    var pass = Number(L.atp_pass_max), fail = Number(L.atp_fail_above);
    if(!(pass >= 0)) pass = 150;
    if(!(fail >= pass)) fail = Math.max(300, pass);
    return { pass: pass, fail: fail };
  }
  function classify(rlu, th){
    if(rlu === null || rlu === undefined || rlu === '' || isNaN(Number(rlu))) return null;
    var v = Number(rlu);
    if(v <= th.pass) return 'pass';
    if(v <= th.fail) return 'caution';
    return 'fail';
  }
  function finalOf(p){ return p.reswab_result || p.result || null; }

  // Days (YYYY-MM-DD) a run occupies, clipped to a sane length.
  function runDays(run){
    var s = run.scheduled_start_date || run.scheduled_date;
    if(!s) return [];
    var e = run.scheduled_end_date || s;
    var out = [], d = new Date(String(s).slice(0,10) + 'T12:00:00Z'), end = new Date(String(e).slice(0,10) + 'T12:00:00Z');
    if(isNaN(d.getTime())) return [];
    if(isNaN(end.getTime()) || end < d) end = d;
    for(var i = 0; i < 60 && d <= end; i++){
      out.push(d.toISOString().slice(0,10));
      d = new Date(d.getTime() + 86400000);
    }
    return out;
  }

  // The tenant-isolation filter. See the header before changing it.
  function selectForClient(records, clientId, clientRuns, opts){
    opts = opts || {};
    var runById = {}, days = {};
    (clientRuns || []).forEach(function(r){
      if(!r || !r.id) return;
      // Defence in depth: a run whose client_id names someone else is not
      // this client's run, whatever the caller passed in.
      if(r.client_id && r.client_id !== clientId) return;
      runById[r.id] = r;
      runDays(r).forEach(function(d){ days[d] = true; });
    });
    var linked = [], facility = [], unsigned = 0;
    (records || []).forEach(function(rec){
      if(!rec || rec.form_code !== FORM_CODE || rec.status === 'voided') return;
      if(rec.client_id && rec.client_id !== clientId) return;
      var runId = rec.run_id || (rec.data && rec.data.run_id) || null;
      var bucket = null;
      if(runId){
        if(runById[runId]) bucket = linked;
      } else if(opts.includeFacility && days[rec.record_date]){
        bucket = facility;
      }
      if(!bucket) return;
      if(rec.status !== 'signed'){
        unsigned++;
        if(opts.signedOnly) return;
      }
      bucket.push(rec);
    });
    return { linked: linked, facility: facility, unsignedMatching: unsigned, runById: runById, productionDays: Object.keys(days).sort() };
  }

  function summarize(recs){
    var s = { points: 0, firstPass: 0, caution: 0, failed: 0, corrected: 0, unresolved: 0 };
    recs.forEach(function(r){
      ((r.data && r.data.points) || []).forEach(function(p){
        if(!p.result) return;
        s.points++;
        if(p.result === 'pass') s.firstPass++;
        if(p.result === 'caution') s.caution++;
        if(p.result === 'fail') s.failed++;
        var f = finalOf(p);
        if(p.result !== 'pass' && f === 'pass') s.corrected++;
        if(f === 'fail') s.unresolved++;
      });
    });
    return s;
  }

