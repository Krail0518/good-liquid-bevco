          client_id: run && run.client_id ? run.client_id : null,
          has_deviation: hasDev,
          deviation_notes: hasDev ? 'ATP FAIL not resolved: ' + unresolved.map(function(p){ return p.location + ' ' + (p.reswab_rlu != null ? p.reswab_rlu : p.rlu) + ' RLU'; }).join(', ') : null,
