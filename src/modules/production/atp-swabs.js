  // ── Customer report ──────────────────────────────────────────
  async function loadClients(){
    var list = (window.clients || []).filter(function(c){ return c && c.id && c.name; });
    if(list.length || !window.supa) return list;
    var r = await window.supa.from('clients').select('id,name').order('name');
    return r.error ? [] : (r.data || []);
  }

  // Runs for one client. Fails closed: any error returns { error }, never a
  // partial list (a partial run list would silently drop swabs, and a report
  // that looks complete but is not is worse than no report).
  async function loadClientRuns(client){
    var cols = 'id, run_name, client_id, client_name, format, lot_number, scheduled_date, scheduled_start_date, scheduled_end_date';
    var a = await window.supa.from('production_runs').select(cols).eq('client_id', client.id);
    if(a.error) return { error: a.error.message || String(a.error) };
    // Older runs carry only the typed client name.
    var b = await window.supa.from('production_runs').select(cols).is('client_id', null).eq('client_name', client.name);
    if(b.error) return { error: b.error.message || String(b.error) };
    return { runs: (a.data || []).concat(b.data || []) };
  }

  async function loadRecords(from, to){
    var r = await window.supa.from('compliance_records').select('*')
      .eq('form_code', FORM_CODE).gte('record_date', from).lte('record_date', to)
      .neq('status', 'voided').order('recorded_at', { ascending: true });
    if(r.error) return { error: r.error.message || String(r.error) };
    return { rows: r.data || [] };
  }

