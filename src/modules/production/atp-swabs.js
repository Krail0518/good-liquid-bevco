  async function loadRecent(){
    if(!window.supa) return { rows: [], error: 'Not connected to the database.' };
    var since = localDate(new Date(Date.now() - 90 * 86400000));
    var r = await window.supa.from('compliance_records').select('*')
      .eq('form_code', FORM_CODE).gte('record_date', since).neq('status', 'voided')
      .order('recorded_at', { ascending: false }).limit(300);
    if(r.error) return { rows: [], error: r.error.message || String(r.error) };
    return { rows: r.data || [], error: null };
  }

