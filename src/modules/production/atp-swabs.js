  window.glAtpSelectForClient = selectForClient;
  window.glAtpSummarize      = summarize;

  // ── Formatting ───────────────────────────────────────────────
  function fmtDate(d){
    if(!d) return '';
    var x = new Date(String(d).length === 10 ? d + 'T12:00:00' : d);
    return isNaN(x.getTime()) ? String(d) : x.toLocaleDateString('en-US', { month:'short', day:'numeric', year:'numeric' });
  }
  function fmtTs(d){
    if(!d) return '';
    var x = new Date(d);
    return isNaN(x.getTime()) ? String(d) : x.toLocaleString('en-US', { month:'short', day:'numeric', year:'numeric', hour:'numeric', minute:'2-digit' });
  }
  function localDate(d){
    var x = d ? new Date(d) : new Date();
    if(isNaN(x.getTime())) x = new Date();
    return x.getFullYear() + '-' + String(x.getMonth()+1).padStart(2,'0') + '-' + String(x.getDate()).padStart(2,'0');
  }
  function localDateTimeInput(d){
    var x = d || new Date();
    return localDate(x) + 'T' + String(x.getHours()).padStart(2,'0') + ':' + String(x.getMinutes()).padStart(2,'0');
  }
  function badge(result){
    if(!result) return '<span style="color:#9aa7bd">—</span>';
    var c = result === 'pass' ? ['#5fcf9e','rgba(95,207,158,.12)'] : result === 'caution' ? ['#f5c842','rgba(245,200,66,.12)'] : ['#ff8579','rgba(231,76,60,.14)'];
    return '<span style="font-size:10px;font-weight:700;letter-spacing:1px;color:' + c[0] + ';background:' + c[1] + ';padding:2px 7px;border-radius:9px">' + RESULT_LABEL[result] + '</span>';
  }
  function runLabel(run){
    if(!run) return '';
    var d = run.scheduled_start_date || run.scheduled_date || '';
    return (d ? fmtDate(d) + ' · ' : '') + (run.run_name || 'Run') + (run.lot_number ? ' · Lot ' + run.lot_number : '');
  }
  function clientNameOf(id){
    var c = (window.clients || []).find(function(x){ return x.id === id; });
    return c ? c.name : '';
  }

